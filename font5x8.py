def draw_text(fb, x, y, text, color=0x00):
    """Draw text onto a framebuffer using the 5x8 font."""
    for ch in text:
        c = ord(ch)
        if c < 32 or c > 126:
            c = 63  # '?'
        idx = (c - 32) * 5
        for col in range(5):
            byte = _FONT[idx + col]
            for row in range(8):
                if byte & (1 << row):
                    fb.pixel(x + col, y + row, color)
        x += CHAR_W


def text_width(text):
    """Return pixel width of text string."""
    if not text:
        return 0
    return len(text) * CHAR_W - SPACING
